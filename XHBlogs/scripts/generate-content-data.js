const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DATA_DIR = path.join(ROOT, 'data');
const OUTPUT_FILE = path.join(DATA_DIR, 'content-data.ts');

const CONTENT_DIRS = {
  moments: path.join(ROOT, 'moments'),
  chatters: path.join(ROOT, 'chatters'),
  posts: path.join(ROOT, 'posts'),
};

function parseMdFile(filePath) {
  const raw = fs.readFileSync(filePath, 'utf-8').replace(/\r\n/g, '\n');
  const match = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) return { data: {}, content: raw };

  const data = {};
  const yamlLines = match[1].split('\n');
  let currentKey = null;
  let currentArray = null;

  for (const line of yamlLines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;

    if (trimmed.startsWith('- ')) {
      if (currentArray) {
        const val = trimmed.slice(2).replace(/^['"](.*)['"]$/, '$1');
        currentArray.push(val);
      }
      continue;
    }

    const colonIdx = line.indexOf(':');
    if (colonIdx === -1) continue;

    let key = line.slice(0, colonIdx).trim();
    let value = line.slice(colonIdx + 1).trim();

    if (value === '' || value === '[]') {
      currentKey = key;
      currentArray = [];
      data[key] = currentArray;
      continue;
    }

    currentKey = null;
    currentArray = null;

    if ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }

    data[key] = value;
  }

  return { data, content: match[2].trim() };
}

function readDir(dir) {
  const items = [];
  if (!fs.existsSync(dir)) return items;
  const files = fs.readdirSync(dir).filter(f => f.endsWith('.md') && f !== '.gitkeep');
  for (const file of files) {
    const filePath = path.join(dir, file);
    const slug = file.replace(/\.md$/, '');
    const { data, content } = parseMdFile(filePath);
    items.push({ slug, ...data, content });
  }
  return items;
}

const moments = readDir(CONTENT_DIRS.moments);
const chatters = readDir(CONTENT_DIRS.chatters);
const posts = readDir(CONTENT_DIRS.posts);

function serialize(items) {
  return JSON.stringify(items, null, 2);
}

const output = `// Auto-generated by scripts/generate-content-data.js
// DO NOT EDIT MANUALLY — run 'npm run build' to regenerate.

export const momentsData = ${serialize(moments)} as const;
export const chattersData = ${serialize(chatters)} as const;
export const postsData = ${serialize(posts)} as const;
`;

if (!fs.existsSync(DATA_DIR)) fs.mkdirSync(DATA_DIR, { recursive: true });
fs.writeFileSync(OUTPUT_FILE, output, 'utf-8');

console.log(`[generate-content-data] Generated ${OUTPUT_FILE}`);
console.log(`  moments: ${moments.length} files`);
console.log(`  chatters: ${chatters.length} files`);
console.log(`  posts: ${posts.length} files`);
