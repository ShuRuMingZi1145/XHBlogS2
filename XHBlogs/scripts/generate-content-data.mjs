import { readFileSync, existsSync, mkdirSync, writeFileSync, readdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { unified } from 'unified';
import remarkParse from 'remark-parse';
import remarkGfm from 'remark-gfm';
import remarkMath from 'remark-math';
import remarkRehype from 'remark-rehype';
import rehypeHighlight from 'rehype-highlight';
import rehypeKatex from 'rehype-katex';
import rehypeStringify from 'rehype-stringify';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const DATA_DIR = resolve(ROOT, 'data');
const OUTPUT_FILE = resolve(DATA_DIR, 'content-data.ts');

const CONTENT_DIRS = {
  moments: resolve(ROOT, 'moments'),
  chatters: resolve(ROOT, 'chatters'),
  posts: resolve(ROOT, 'posts'),
};

function parseMdFile(filePath) {
  const raw = readFileSync(filePath, 'utf-8').replace(/\r\n/g, '\n');
  const match = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) return { data: {}, content: raw };

  const data = {};
  const yamlLines = match[1].split('\n');
  let currentKey = null;
  let currentArray = null;

  for (const line of yamlLines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;

    if (trimmed.startsWith('- ')) {
      if (currentArray) {
        const val = trimmed.slice(2).replace(/^['"](.*)['"]$/, '$1');
        currentArray.push(val);
      }
      continue;
    }

    const colonIdx = line.indexOf(':');
    if (colonIdx === -1) continue;

    let key = line.slice(0, colonIdx).trim();
    let value = line.slice(colonIdx + 1).trim();

    if (value === '' || value === '[]') {
      currentKey = key;
      currentArray = [];
      data[key] = currentArray;
      continue;
    }

    currentKey = null;
    currentArray = null;

    if ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }

    data[key] = value;
  }

  return { data, content: match[2].trim() };
}

async function mdToHtml(md) {
  let content = md;

  content = content.replace(/\r\n/g, '\n');
  content = content.replace(/[\u200B-\u200D\uFEFF]/g, '');
  content = content.replace(/^[ \t]+$/gm, '');
  content = content.replace(/^(\s*\d+)\.([^ \n])/gm, '$1. $2');

  const blocks = content.split(/(```[\s\S]*?```|~~~[\s\S]*?~~~)/g);
  content = blocks.map((block, index) => {
    if (index % 2 === 1) {
      if (/^```[ \t]*(\n|$)/.test(block)) {
        return block.replace(/^```[ \t]*/, '```cpp');
      }
      return block;
    }
    return block.replace(/\n{3,}/g, (match) => {
      const brCount = match.length - 2;
      return '\n\n' + '<br>'.repeat(brCount) + '\n\n';
    });
  }).join('');

  const processed = await unified()
    .use(remarkParse)
    .use(remarkGfm)
    .use(remarkMath)
    .use(remarkRehype, { allowDangerousHtml: true })
    .use(rehypeHighlight, {
      detect: true,
      ignoreMissing: true,
      subset: ['cpp', 'c', 'python', 'java', 'javascript', 'typescript', 'go', 'rust', 'bash', 'json', 'html', 'css', 'sql', 'xml']
    })
    .use(rehypeKatex)
    .use(rehypeStringify, { allowDangerousHtml: true })
    .process(content);

  return processed.toString();
}

async function readDir(dir) {
  const items = [];
  if (!existsSync(dir)) return items;
  const files = readdirSync(dir).filter(f => f.endsWith('.md') && f !== '.gitkeep');
  for (const file of files) {
    const filePath = resolve(dir, file);
    const slug = file.replace(/\.md$/, '');
    const { data, content } = parseMdFile(filePath);
    const contentHtml = await mdToHtml(content);
    items.push({ slug, ...data, content, contentHtml });
  }
  return items;
}

async function main() {
  const moments = await readDir(CONTENT_DIRS.moments);
  const chatters = await readDir(CONTENT_DIRS.chatters);
  const posts = await readDir(CONTENT_DIRS.posts);

  function serialize(items) {
    return JSON.stringify(items, null, 2);
  }

  const output = `// Auto-generated by scripts/generate-content-data.mjs
// DO NOT EDIT MANUALLY — run 'npm run build' to regenerate.

export const momentsData = ${serialize(moments)} as const;
export const chattersData = ${serialize(chatters)} as const;
export const postsData = ${serialize(posts)} as const;
`;

  if (!existsSync(DATA_DIR)) mkdirSync(DATA_DIR, { recursive: true });
  writeFileSync(OUTPUT_FILE, output, 'utf-8');

  console.log(`[generate-content-data] Generated ${OUTPUT_FILE}`);
  console.log(`  moments: ${moments.length} files`);
  console.log(`  chatters: ${chatters.length} files`);
  console.log(`  posts: ${posts.length} files`);
}

main().catch(err => {
  console.error('[generate-content-data] Error:', err);
  process.exit(1);
});
